/**
 * Turns what the browser hands over on upload -- an <input type="file">
 * selection (plain or `webkitdirectory`) or a drag-and-drop DataTransfer --
 * into a flat list of files, each carrying the path RELATIVE to the drop
 * target ("site/css/app.css"), so a whole folder is recreated on the host
 * by uploading each file to `<destination>/<relativePath>`.
 */

export interface PendingUpload {
  file: File;
  relativePath: string;
}

export function filesFromInput(list: FileList | null): PendingUpload[] {
  return Array.from(list ?? []).map((file) => ({
    file,
    // Set by <input webkitdirectory>: "folder/sub/file.txt"; "" for a plain pick.
    relativePath: file.webkitRelativePath || file.name,
  }));
}

// Minimal shapes of the (still non-standard, but universally shipped)
// FileSystem Entry API that drag-and-drop of folders relies on.
interface FsEntryLike {
  isFile: boolean;
  isDirectory: boolean;
  name: string;
  file?: (success: (file: File) => void, error?: (err: unknown) => void) => void;
  createReader?: () => { readEntries: (success: (entries: FsEntryLike[]) => void, error?: (err: unknown) => void) => void };
}

function readAllEntries(entry: FsEntryLike): Promise<FsEntryLike[]> {
  const reader = entry.createReader!();
  const all: FsEntryLike[] = [];
  // readEntries returns at most ~100 entries per call; loop until empty.
  return new Promise((resolve, reject) => {
    const next = () =>
      reader.readEntries((batch) => {
        if (batch.length === 0) resolve(all);
        else {
          all.push(...batch);
          next();
        }
      }, reject);
    next();
  });
}

async function walk(entry: FsEntryLike, prefix: string, out: DroppedFiles): Promise<void> {
  const relativePath = prefix ? `${prefix}/${entry.name}` : entry.name;
  if (entry.isFile && entry.file) {
    const file = await new Promise<File>((resolve, reject) => entry.file!(resolve, reject));
    out.uploads.push({ file, relativePath });
  } else if (entry.isDirectory) {
    // A dropped project with node_modules/.venv is tens of thousands of
    // entries read one callback at a time -- the freeze. Not read at all;
    // the review dialog lists them as left out.
    if (HEAVY_DIR_NAMES.has(entry.name)) {
      out.unreadDirs.push(relativePath);
      return;
    }
    for (const child of await readAllEntries(entry)) await walk(child, relativePath, out);
  }
}

/** True when the drag carries files from the OS (vs. an internal item drag). */
export function isExternalFileDrag(dataTransfer: DataTransfer): boolean {
  return Array.from(dataTransfer.types).includes("Files");
}

export interface DroppedFiles {
  uploads: PendingUpload[];
  /** Heavy folders (see HEAVY_DIR_NAMES) skipped without being read. */
  unreadDirs: string[];
}

export async function filesFromDataTransfer(dataTransfer: DataTransfer): Promise<DroppedFiles> {
  // Entries must be grabbed synchronously, before the first await -- the
  // DataTransfer is emptied once the drop event handler yields.
  const entries = Array.from(dataTransfer.items)
    .filter((item) => item.kind === "file")
    .map((item) => (item as DataTransferItem & { webkitGetAsEntry?: () => FsEntryLike | null }).webkitGetAsEntry?.() ?? null);
  if (entries.length === 0 || entries.some((entry) => entry === null)) {
    return { uploads: filesFromInput(dataTransfer.files), unreadDirs: [] };
  }
  const out: DroppedFiles = { uploads: [], unreadDirs: [] };
  for (const entry of entries) await walk(entry!, "", out);
  return out;
}

/** Top-level names an upload batch would create in the destination. */
export function topLevelNames(uploads: PendingUpload[]): string[] {
  return Array.from(new Set(uploads.map((u) => u.relativePath.split("/")[0])));
}

// ---- upload review ---------------------------------------------------------

/** Upload limits checked before anything is sent. A file over nginx's
 * `client_max_body_size` (60m, frontend/nginx.conf) would only fail after
 * being transferred; the file count keeps one batch from flooding the bridge
 * (one request per file) and the browser (one progress row per file). */
export const UPLOAD_MAX_FILES = 1000;
export const UPLOAD_MAX_FILE_BYTES = 60 * 1024 * 1024;
export const UPLOAD_MAX_TOTAL_BYTES = 2 * 1024 * 1024 * 1024;

/** Folders that are regenerated by tooling rather than written by hand --
 * what usually turns "upload my project" into tens of thousands of files. */
export const HEAVY_DIR_NAMES = new Set([
  "node_modules",
  ".git",
  ".venv",
  "venv",
  "__pycache__",
  ".pytest_cache",
  ".mypy_cache",
  ".ruff_cache",
  ".tox",
  ".next",
  ".cache",
]);

export interface HeavyDir {
  path: string;
  files: number;
  bytes: number;
}

export interface UploadSummary {
  files: number;
  folders: number;
  bytes: number;
  /** Heavy folders present in the selection, outermost only. */
  heavyDirs: HeavyDir[];
  oversized: PendingUpload[];
}

/** The outermost heavy folder a relative path sits inside, or null. */
function heavyDirOf(relativePath: string): string | null {
  const parts = relativePath.split("/");
  for (let i = 0; i < parts.length - 1; i++) {
    if (HEAVY_DIR_NAMES.has(parts[i])) return parts.slice(0, i + 1).join("/");
  }
  return null;
}

export function summarizeUpload(uploads: PendingUpload[]): UploadSummary {
  const folders = new Set<string>();
  const heavy = new Map<string, HeavyDir>();
  let bytes = 0;
  const oversized: PendingUpload[] = [];
  for (const upload of uploads) {
    bytes += upload.file.size;
    if (upload.file.size > UPLOAD_MAX_FILE_BYTES) oversized.push(upload);
    const parts = upload.relativePath.split("/");
    for (let i = 1; i < parts.length; i++) folders.add(parts.slice(0, i).join("/"));
    const dir = heavyDirOf(upload.relativePath);
    if (dir) {
      const entry = heavy.get(dir) ?? { path: dir, files: 0, bytes: 0 };
      entry.files += 1;
      entry.bytes += upload.file.size;
      heavy.set(dir, entry);
    }
  }
  return {
    files: uploads.length,
    folders: folders.size,
    bytes,
    heavyDirs: Array.from(heavy.values()).sort((a, b) => b.files - a.files),
    oversized,
  };
}

/** The selection minus everything inside a heavy folder. */
export function withoutHeavyDirs(uploads: PendingUpload[]): PendingUpload[] {
  return uploads.filter((upload) => heavyDirOf(upload.relativePath) === null);
}

export type UploadBlock = "empty" | "tooManyFiles" | "tooLarge";

/** Why this batch can't be sent as is, or null when it can. Oversized
 * files don't block: they are left out and listed. */
export function uploadBlock(summary: UploadSummary): UploadBlock | null {
  const sendable = summary.files - summary.oversized.length;
  if (sendable === 0) return "empty";
  if (sendable > UPLOAD_MAX_FILES) return "tooManyFiles";
  const oversizedBytes = summary.oversized.reduce((sum, u) => sum + u.file.size, 0);
  if (summary.bytes - oversizedBytes > UPLOAD_MAX_TOTAL_BYTES) return "tooLarge";
  return null;
}
